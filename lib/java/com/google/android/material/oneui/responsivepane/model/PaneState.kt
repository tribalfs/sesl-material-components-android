package com.google.android.material.oneui.responsivepane.model

/**
 * Settled states of a responsive drawer; the closed state can retain a visible narrow rail.
 */
enum class PaneState {
	/**
	 * Drawer at its configured opened width.
	 */
	OPENED,
	/**
	 * Drawer at its configured closed width.
	 */
	CLOSED
}
