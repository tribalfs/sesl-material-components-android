package com.google.android.material.oneui.responsivepane.helper

/**
 * Layout modes used to select responsive pane elevation presets.
 */
enum class ResponsivePaneLayoutMode {
	/**
	 * Mode with an elevated opened drawer and a flat closed drawer.
	 */
	MEDIUM,
	/**
	 * Mode with flat drawer elevation in both states.
	 */
	LARGE
}
